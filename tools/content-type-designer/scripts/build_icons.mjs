// Writes src/icons.ts: the Lucide icons the mobile mock draws, copied from the
// app's own @lucide/svelte package so the shapes match the real page exactly.
// Run from the repo root after `pnpm install` in frontend/:
//   node tools/content-type-designer/scripts/build_icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(here, '../../../frontend/node_modules/@lucide/svelte/dist/icons');
const NAMES = [
  'plus',
  'glasses',
  'list-plus',
  'play',
  'settings',
  'search',
  'sliders-horizontal',
  'chevron-left',
  'chevron-right',
  'x',
  'list-x',
  'list-ordered',
  'arrow-up-down',
  'message-circle'
];

const attrs = (o) => Object.entries(o).map(([k, v]) => `${k}="${v}"`).join(' ');
const out = {};
for (const name of NAMES) {
  const src = readFileSync(join(iconsDir, `${name}.svelte`), 'utf8');
  const json = src.match(/const iconData = (\{.*?\});\n/s)?.[1];
  if (!json) throw new Error(`no iconData in ${name}`);
  const data = JSON.parse(json);
  out[name] = data.node.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
}
const version = readFileSync(join(iconsDir, 'plus.svelte'), 'utf8').match(/@lucide\/svelte v([\d.]+)/)?.[1] ?? '?';

const body = `/**
 * Generated by scripts/build_icons.mjs from @lucide/svelte v${version} (ISC). Do not edit.
 * Inner SVG markup of each icon on a 24×24 grid, drawn by lucideSvg().
 */
export const LUCIDE: Record<string, string> = ${JSON.stringify(out, null, 2)};

/** The markup Lucide's Icon.svelte renders: stroke 2, round caps and joins, currentColor. */
export function lucideSvg(name: string, size: number, extraClass = ''): string {
  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide \${extraClass}">\${LUCIDE[name] ?? ''}</svg>\`;
}
`;
writeFileSync(join(here, '../src/icons.ts'), body);
console.log(`wrote src/icons.ts (${NAMES.length} icons, lucide v${version})`);
