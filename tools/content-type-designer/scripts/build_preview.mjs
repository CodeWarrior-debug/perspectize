// Rebuild a single-type Activity preview by re-embedding a spec JSON into an
// existing generated preview (the renderer is identical across types).
// Stand-in for .claude/skills/content-type-preview/build.mjs, which is not on main.
//   node scripts/build_preview.mjs <spec.json> <out.html> [template.html]
import { readFileSync, writeFileSync } from 'node:fs';

const [specPath, outPath, tplPath = new URL('../previews/movie-activity.html', import.meta.url)] = process.argv.slice(2);
if (!specPath || !outPath) { console.error('usage: build_preview.mjs <spec.json> <out.html> [template.html]'); process.exit(2); }

const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const MAX_COLS = 10;
const labelled = spec.columns.filter((c) => c.kind !== 'perspectize').length + 1;
if (labelled > MAX_COLS) { console.error(`${labelled} columns; the preview caps at ${MAX_COLS}`); process.exit(1); }
for (const r of spec.rows) if (!r.details?.title) { console.error(`row ${r.id} has no details.title`); process.exit(1); }

// Extra icons not in the template's ICONS map.
const EXTRA_ICONS = {
  food: '<path d="M12 7c-1.5-2-5-2.5-6.5 0S4 14 6 17.5 10 21 12 20c2 1 4 1 6-2.5S20.5 9.5 18.5 7 13.5 5 12 7z"/><path d="M12 7c0-2 1-3.5 3-4"/>',
};

let html = readFileSync(tplPath, 'utf8');
const json = JSON.stringify(spec).replace(/</g, '\\u003c');
const before = html;
html = html.replace(/<script>const SPEC = .*?;<\/script>/s, () => `<script>const SPEC = ${json};</script>`);
if (html === before) { console.error('SPEC script not found in template'); process.exit(1); }
html = html.replace(/<title>.*?<\/title>/, `<title>${spec.type.label.replace(/&/g, '&amp;')} · Activity preview</title>`);
html = html.replace(/--accent:#[0-9A-Fa-f]{3,8}/, `--accent:${spec.type.accent}`);
html = html.replace('const ICONS = {', () => `const ICONS = {\n${Object.entries(EXTRA_ICONS).map(([k, v]) => `  ${k}:'${v}',`).join('\n')}`);
html = html.replace('Generated by .claude/skills/content-type-preview/build.mjs', 'Generated by tools/content-type-designer/scripts/build_preview.mjs');
writeFileSync(outPath, html);
console.log(`wrote ${outPath} (${spec.columns.length} columns, ${spec.rows.length} rows)`);
