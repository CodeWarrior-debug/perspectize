"""Regenerate src/lib/utils/grid-header-metrics.ts from the self-hosted Geist font.

The Activity grid's header labels are Geist at weight 600. This reads the real
advance width of every printable ASCII glyph at that weight, so column minimum
widths come from the font itself rather than an average-character guess.

Run from frontend/ after replacing static/fonts/Geist-Variable.woff2:
    python3 -m pip install fonttools brotli
    python3 scripts/gen-header-metrics.py
"""

from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

FONT = Path("static/fonts/Geist-Variable.woff2")
OUT = Path("src/lib/utils/grid-header-metrics.ts")
WEIGHT = 600  # GRID_THEME_PARAMS.headerFontWeight

font = instantiateVariableFont(TTFont(FONT), {"wght": WEIGHT})
upm = font["head"].unitsPerEm
cmap = font.getBestCmap()
hmtx = font["hmtx"]

rows = []
for code in range(32, 127):
    em = hmtx[cmap[code]][0] / upm
    rows.append(f"\t{code - 32}: {em:.4f}, // {chr(code)!r}")
widest = max(hmtx[cmap[c]][0] for c in range(32, 127)) / upm

OUT.write_text(
    f"""// GENERATED by scripts/gen-header-metrics.py from {FONT} at wght {WEIGHT}. Do not edit by hand.
//
// Advance width, in em, of each printable ASCII glyph (index = char code - 32) in the grid's
// header font. Column minimum widths are built from these, so a header label's width is the
// font's own measurement rather than an average-character estimate.

/** Advance widths (em) for char codes 32-126, indexed by code - 32. */
export const GEIST_SEMIBOLD_ADVANCE_EM: Readonly<Record<number, number>> = {{
{chr(10).join(rows)}
}};

/** Widest printable ASCII glyph (em): the stand-in for any character outside the table. */
export const GEIST_SEMIBOLD_WIDEST_EM = {widest:.4f};
"""
)
print(f"wrote {OUT}")
