#!/usr/bin/env node
// Build a single-type Activity preview (one self-contained HTML file) from a spec JSON.
//
//   node .claude/skills/content-type-preview/build.mjs <spec.json> <out.html> [--no-thumbs]
//
// Exit codes: 0 built · 1 spec invalid (errors listed) · 2 usage / IO error.
//
// The renderer lives in template.html; this script validates the spec, inlines
// thumbnails, and fills the template's /*@SPEC@*/, /*@TITLE@*/ and /*@ACCENT@*/ slots.
// Thumbnails: any http(s) `cells.item.thumb` or `details.media` that has an entry in
// tools/content-type-designer/src/thumbs.ts (generated by scripts/build_thumbs.py) is
// replaced by that data URI, so the page renders offline and inside a claude.ai artifact
// (whose CSP blocks remote images). Unmatched URLs are kept and reported as warnings.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../../..');
const TEMPLATE = resolve(HERE, 'template.html');
const THUMBS_TS = resolve(REPO, 'tools/content-type-designer/src/thumbs.ts');

const MAX_COLUMNS = 10; // the designer's crowding threshold (model.ts: visibleCount > 10)
const KINDS = ['perspectize', 'item', 'pill', 'text', 'num', 'tags', 'date'];
const STATUSES = ['shipped', 'planned', 'proposed'];
const FILLS = ['full', 'partial', 'sparse'];
const ICONS = ['book', 'film', 'music', 'image', 'tv', 'file', 'quote', 'food'];

const args = process.argv.slice(2);
const noThumbs = args.includes('--no-thumbs');
const [specPath, outPath] = args.filter((a) => !a.startsWith('--'));
if (!specPath || !outPath) {
  console.error('usage: build.mjs <spec.json> <out.html> [--no-thumbs]');
  process.exit(2);
}

let spec;
try {
  spec = JSON.parse(readFileSync(specPath, 'utf8'));
} catch (e) {
  console.error(`cannot read ${specPath}: ${e.message}`);
  process.exit(2);
}

// ---------------------------------------------------------------- validate
const errors = [];
const warnings = [];
const err = (m) => errors.push(m);
const warn = (m) => warnings.push(m);
const isStr = (v) => typeof v === 'string' && v.length > 0;

const t = spec.type ?? {};
if (!isStr(t.label)) err('type.label is required');
if (!isStr(t.enumValue) || !/^[A-Z][A-Z0-9_]*$/.test(t.enumValue)) err('type.enumValue must be UPPER_SNAKE (e.g. FOOD_ITEM)');
if (!/^#[0-9A-Fa-f]{6}$/.test(t.accent ?? '')) err('type.accent must be a #rrggbb colour');
if (t.icon && !ICONS.includes(t.icon)) warn(`type.icon "${t.icon}" is not in the template (${ICONS.join(', ')}); the file icon is used`);
if (!/^\d{4}-\d{2}-\d{2}$/.test(spec.meta?.date ?? '')) err('meta.date must be YYYY-MM-DD');

const cols = Array.isArray(spec.columns) ? spec.columns : (err('columns must be an array'), []);
const colIds = new Set();
cols.forEach((c, i) => {
  const at = `columns[${i}]${c?.id ? ` (${c.id})` : ''}`;
  if (!isStr(c?.id)) return err(`${at}: id is required`);
  if (colIds.has(c.id)) err(`${at}: duplicate column id`);
  colIds.add(c.id);
  if (!KINDS.includes(c.kind)) err(`${at}: kind must be one of ${KINDS.join(', ')}`);
  if (!STATUSES.includes(c.status)) err(`${at}: status must be one of ${STATUSES.join(', ')}`);
  if (c.kind !== 'perspectize' && !isStr(c.label)) err(`${at}: label is required`);
  if (!isStr(c.header?.body)) err(`${at}: header.body (the header tooltip) is required`);
  if (!isStr(c.header?.src)) warn(`${at}: header.src is empty — say where the value comes from`);
  if (!['perspectize', 'item'].includes(c.kind) && !isStr(c.cell?.whenEmpty)) warn(`${at}: cell.whenEmpty is empty — say what a blank cell means (missing is not zero)`);
});
if (cols.length > MAX_COLUMNS) err(`${cols.length} columns; the preview caps at ${MAX_COLUMNS} (move the rest to the column picker / details view)`);
if (cols[0]?.kind !== 'perspectize') warn('the first column is usually the Perspectize ◎ column');
if (!cols.some((c) => c.kind === 'item')) err('one column must have kind "item"');

const rows = Array.isArray(spec.rows) ? spec.rows : (err('rows must be an array'), []);
if (rows.length === 0) err('at least one row is required');
const rowIds = new Set();
rows.forEach((r, i) => {
  const at = `rows[${i}]${r?.id != null ? ` (id ${r.id})` : ''}`;
  if (r?.id == null) return err(`${at}: id is required`);
  if (rowIds.has(String(r.id))) err(`${at}: duplicate row id`);
  rowIds.add(String(r.id));
  if (!FILLS.includes(r.fill)) err(`${at}: fill must be one of ${FILLS.join(', ')}`);
  if (typeof r.cells !== 'object' || r.cells === null) return err(`${at}: cells is required`);
  for (const k of Object.keys(r.cells)) if (!colIds.has(k)) warn(`${at}: cell "${k}" has no column (ignored by the grid)`);
  const item = r.cells[cols.find((c) => c.kind === 'item')?.id];
  if (!isStr(item?.title)) err(`${at}: the item cell needs a title`);
  if (!isStr(r.details?.title)) err(`${at}: details.title is required (the modal opens from every row)`);
  for (const tile of r.details?.tiles ?? []) {
    if (tile.status && !STATUSES.includes(tile.status)) err(`${at}: tile "${tile.k}" has status "${tile.status}"`);
    if ((tile.v == null || tile.v === '') && !isStr(tile.empty)) warn(`${at}: tile "${tile.k}" is empty with no "empty" reason`);
  }
});
if (rows.length && !rows.some((r) => r.fill === 'sparse')) warn('no sparse row — include one so empty-cell states are visible');
if (!spec.perspective) err('perspective is required ({ ratings, addFieldHint })');

if (errors.length) {
  console.error(`✗ ${specPath}: ${errors.length} error(s)`);
  for (const e of errors) console.error(`  - ${e}`);
  for (const w of warnings) console.error(`  ! ${w}`);
  process.exit(1);
}

// ---------------------------------------------------------------- thumbnails
let inlined = 0;
if (!noThumbs) {
  const thumbs = existsSync(THUMBS_TS) ? parseThumbs(readFileSync(THUMBS_TS, 'utf8')) : {};
  const inline = (url, where) => {
    if (!isStr(url) || !/^https?:/.test(url)) return url;
    if (thumbs[url]) return inlined++, thumbs[url];
    warn(`${where}: ${url} is not in src/thumbs.ts — add it to the designer catalog and run scripts/build_thumbs.py, or it won't render in an artifact`);
    return url;
  };
  for (const r of rows) {
    const item = r.cells[cols.find((c) => c.kind === 'item').id];
    if (item?.thumb) item.thumb = inline(item.thumb, `row ${r.id} thumb`);
    if (r.details?.media) r.details.media = inline(r.details.media, `row ${r.id} details.media`);
  }
}

function parseThumbs(ts) {
  const out = {};
  for (const m of ts.matchAll(/^\s*("(?:[^"\\]|\\.)*"):\s*("(?:[^"\\]|\\.)*"),?$/gm)) out[JSON.parse(m[1])] = JSON.parse(m[2]);
  return out;
}

// ---------------------------------------------------------------- render
const escHtml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');
let html = readFileSync(TEMPLATE, 'utf8');
const slots = [
  ['/*@SPEC@*/null', JSON.stringify(spec).replace(/</g, '\\u003c')],
  ['/*@TITLE@*/', escHtml(t.label)],
  ['/*@ACCENT@*/', t.accent]
];
for (const [slot, value] of slots) {
  if (!html.includes(slot)) {
    console.error(`template.html has no ${slot} slot`);
    process.exit(2);
  }
  html = html.replace(slot, () => value);
}
writeFileSync(outPath, html);

for (const w of warnings) console.error(`  ! ${w}`);
console.log(`✓ ${outPath}: ${cols.length} columns, ${rows.length} rows, ${inlined} inlined image(s), ${warnings.length} warning(s)`);
